#!/usr/bin/env node
// PreToolUse hook (Edit|Write): stops hand-edits to secrets, lockfiles and generated output.
// Exit 2 = block with a reason Claude can act on. Tune PROTECTED for your project.
import { readFileSync } from 'node:fs';

let filePath = '';
try {
  const input = JSON.parse(readFileSync(0, 'utf8') || '{}');
  filePath = String(input?.tool_input?.file_path ?? '');
} catch {
  process.exit(0);
}
if (!filePath.trim()) process.exit(0);
const p = filePath.replace(/\\/g, '/');

const PROTECTED = [
  [/(^|\/)\.env(\.(?!example$|sample$|template$)[^/]*)?$/i, 'env files hold secrets; edit .env.example instead and tell the user which values to add'],
  [/\.(pem|key|pfx|p12|crt)$/i, 'key/certificate file'],
  [/(^|\/)\.git\//, 'git internals'],
  [/(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|uv\.lock|poetry\.lock|Pipfile\.lock)$/i, 'lockfile; change dependencies with the package manager (e.g. uv add, npm install) instead'],
  [/(^|\/)next-env\.d\.ts$/, 'generated by the framework'],
  [/(^|\/)(node_modules|\.venv|venv|__pycache__|\.next|dist|coverage|\.pytest_cache|\.mypy_cache|\.ruff_cache)\//, 'generated/vendored output; change the source instead'],
  [/(^|\/)(generated|__generated__)\//, 'generated API client/types; change the backend schema and re-run the client generation command from CLAUDE.md'],
];

for (const [re, why] of PROTECTED) {
  if (re.test(p)) {
    process.stderr.write(`Blocked by .claude/hooks/protect-files.mjs: ${why}. File: ${filePath}\n`);
    process.exit(2);
  }
}
process.exit(0);
